#!/usr/bin/env node
/**
 * Regenerates `src/lib/timezone-countries.generated.ts`, the zone → ISO country
 * code table the timezone combobox needs to make "spain" match `Europe/Madrid`
 * (the IANA id never carries the country).
 *
 * Re-run it when Node's bundled tzdata changes — a couple of times a year —
 * and commit the result:
 *
 *   node backoffice/scripts/generate-timezone-countries.mjs
 *
 * The country codes come from `COUNTRIES` in shared-form-ui, and asking only
 * for *those* codes matters: `Intl.Locale#getTimeZones` still answers for
 * retired tzdata codes (AN, BU, CS, DD, RH…), and iterating A→Z without the
 * filter lets them claim zones ahead of the country that actually owns them.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const COUNTRIES_TS = resolve(
  here,
  "../../packages/shared-form-ui/src/data/countries.ts",
)
const OUT = resolve(here, "../src/lib/timezone-countries.generated.ts")

/** ISO codes declared in shared-form-ui's COUNTRIES list, in file order. */
function readIsoCodes() {
  const source = readFileSync(COUNTRIES_TS, "utf8")
  const codes = [...source.matchAll(/code:\s*"([A-Z]{2})"/g)].map((m) => m[1])
  if (codes.length === 0) {
    throw new Error(`No country codes found in ${COUNTRIES_TS}`)
  }
  return codes
}

const canonical = new Set(Intl.supportedValuesOf("timeZone"))
const byZone = new Map()
const conflicts = []

for (const code of readIsoCodes()) {
  let zones
  try {
    zones = new Intl.Locale(`en-${code}`).getTimeZones()
  } catch {
    continue // ICU rejects the region — nothing to map.
  }
  for (const zone of zones ?? []) {
    if (!canonical.has(zone)) continue
    const owner = byZone.get(zone)
    if (owner === undefined) byZone.set(zone, code)
    else if (owner !== code) conflicts.push(`${zone}: ${owner} vs ${code}`)
  }
}

const mapped = [...byZone.keys()].sort()
const unmapped = [...canonical].filter((z) => !byZone.has(z)).sort()

const body = mapped.map((z) => `  ${JSON.stringify(z)}: "${byZone.get(z)}",`)
writeFileSync(
  OUT,
  `// Generated by scripts/generate-timezone-countries.mjs — do not edit by hand.
// tzdata via Node ${process.version}, ${canonical.size} canonical IANA zones, ${mapped.length} mapped.
export const TIMEZONE_COUNTRY: Record<string, string> = {
${body.join("\n")}
}
`,
  "utf8",
)

console.log(`canonical zones: ${canonical.size}`)
console.log(`mapped to a country: ${mapped.length}`)
console.log(`zones without a country: ${unmapped.length}`)
if (unmapped.length > 0) console.log(`  ${unmapped.join(", ")}`)
console.log(`conflicts: ${conflicts.length}`)
if (conflicts.length > 0) console.log(`  ${conflicts.join("\n  ")}`)
console.log(`wrote ${OUT}`)
